-- A persistent, admin-curated set of flood-prone zones (pin + radius), plus nullable geometry
-- on flood_alert so a manual "Warn" against a zone can be proximity-gated by the client.
-- NULL geometry on flood_alert = global alert (all existing rows) = unchanged behavior.
-- GET /flood-prone is public; writes and /flood-prone/all are ADMIN-only.
-- ============================================================================
SET search_path TO baha, public;

CREATE TABLE IF NOT EXISTS flood_prone_area (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100000) PRIMARY KEY,
    name            TEXT NOT NULL,
    district        TEXT NOT NULL,
    latitude        NUMERIC(9,6) NOT NULL,
    longitude       NUMERIC(9,6) NOT NULL,
    radius_m        INTEGER NOT NULL DEFAULT 500,
    level           alert_level_t NOT NULL DEFAULT 'orange',
    note            TEXT,
    active          BOOLEAN NOT NULL DEFAULT true,
    last_warned_at  TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT flood_prone_area_radius_check CHECK (radius_m BETWEEN 50 AND 20000)
);
CREATE OR REPLACE TRIGGER trg_flood_prone_area_updated_at
    BEFORE UPDATE ON flood_prone_area
    FOR EACH ROW EXECUTE FUNCTION baha.fn_set_updated_at();
CREATE INDEX IF NOT EXISTS idx_flood_prone_area_active ON flood_prone_area (active);

-- Geo-stamp on alerts: NULL = global alert (all existing rows), non-NULL = proximity-gated.
ALTER TABLE flood_alert ADD COLUMN IF NOT EXISTS latitude  NUMERIC(9,6);
ALTER TABLE flood_alert ADD COLUMN IF NOT EXISTS longitude NUMERIC(9,6);
ALTER TABLE flood_alert ADD COLUMN IF NOT EXISTS radius_m  INTEGER;
ALTER TABLE flood_alert ADD COLUMN IF NOT EXISTS area_id   INTEGER
    REFERENCES flood_prone_area(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_flood_alert_area_id ON flood_alert (area_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES    IN SCHEMA baha TO baha_user;
GRANT USAGE, SELECT                  ON ALL SEQUENCES IN SCHEMA baha TO baha_user;

ANALYZE flood_prone_area, flood_alert;
