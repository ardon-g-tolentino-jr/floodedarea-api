-- Adds draft_incident: flood incidents the ingestion job drafts from news, awaiting admin review.
-- Approving a draft creates a system flood_report; the human is the gate. Reuses severity_t/trend_t/
-- road_t; adds incident_status_t ('pending','approved','dismissed'). Deduped on source_url (UNIQUE).
