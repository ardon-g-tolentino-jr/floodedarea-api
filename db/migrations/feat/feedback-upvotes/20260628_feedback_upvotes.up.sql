-- One row per (feedback, voter) so anyone — full account or no-login guest, keyed by their
-- app_user id — counts once; re-voting is a toggle (delete the row). A feedback item's total
-- upvotes is the count of its rows. ON DELETE CASCADE keeps votes tidy when a user or feedback
-- item is removed.
-- ============================================================================
SET search_path TO baha, public;

CREATE TABLE IF NOT EXISTS feedback_upvote (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_id INTEGER NOT NULL REFERENCES feedback(id) ON DELETE CASCADE,
    user_id     INTEGER NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_feedback_upvote UNIQUE (feedback_id, user_id)
);

-- Index every column used in WHERE/JOIN. The unique constraint already indexes (feedback_id, user_id)
-- — which also serves count-by-feedback and the toggle's exists/delete — so we only add user_id for
-- the "which items has this caller upvoted" lookup.
CREATE INDEX IF NOT EXISTS idx_feedback_upvote_user ON feedback_upvote(user_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES    IN SCHEMA baha TO baha_user;
GRANT USAGE, SELECT                  ON ALL SEQUENCES IN SCHEMA baha TO baha_user;

ANALYZE feedback_upvote;
