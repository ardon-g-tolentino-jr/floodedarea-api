SET search_path TO baha, public;

CREATE TABLE IF NOT EXISTS social_post (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100000) PRIMARY KEY,
    report_id     INTEGER NOT NULL REFERENCES flood_report(id) ON DELETE CASCADE,
    network       VARCHAR(16) NOT NULL,                    -- 'facebook' | 'x'
    status        VARCHAR(16) NOT NULL DEFAULT 'pending',   -- pending|sent|failed|skipped
    external_id   VARCHAR(64),                              -- FB post id / tweet id
    external_url  TEXT,
    caption       TEXT,
    attempts      INTEGER NOT NULL DEFAULT 0,
    last_error    TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT social_post_report_network_uk UNIQUE (report_id, network)
);

CREATE INDEX IF NOT EXISTS social_post_report_idx ON social_post (report_id);
CREATE INDEX IF NOT EXISTS social_post_status_idx ON social_post (status, created_at);

CREATE OR REPLACE TRIGGER trg_social_post_updated_at
    BEFORE UPDATE ON social_post
    FOR EACH ROW EXECUTE FUNCTION baha.fn_set_updated_at();

-- Global kill switches (admin panel toggles), default ON — auto-post is opt-in per report already
-- via the admin's per-report checkboxes; these just let an admin pause a whole network.
INSERT INTO app_setting (key, value) VALUES ('social_autopost_facebook', 'true')
    ON CONFLICT (key) DO NOTHING;
INSERT INTO app_setting (key, value) VALUES ('social_autopost_x', 'true')
    ON CONFLICT (key) DO NOTHING;

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES    IN SCHEMA baha TO baha_user;
GRANT USAGE, SELECT                  ON ALL SEQUENCES IN SCHEMA baha TO baha_user;

ANALYZE social_post, app_setting;
