-- Tracks each attempt to publish an admin "system" flood report to the FloodedArea Facebook Page
-- and X account. GET /social-posts and POST /social-posts/{id}/retry are ADMIN-only. Two
-- app_setting rows give a no-deploy kill switch per network (mirrors chat_enabled).
